#!/usr/bin/env python3

import json
import subprocess
import sys
from ipaddress import IPv4Network, IPv6Network, collapse_addresses
from typing import Any


def eprint(s: str) -> None:
    print(s, file=sys.stderr)


def ip_j(*args: str) -> list[dict[str, Any]]:
    proc = subprocess.run(
        ["ip", "-j", *args],
        capture_output=True,
        text=True,
        check=True,
    )
    return json.loads(proc.stdout)


def fetch_ips() -> tuple[set[IPv4Network], set[IPv6Network]]:
    local_v4 = set()
    local_v6 = set()
    for r in ip_j("-4", "route", "show", "table", "local", "type", "local"):
        local_v4.add(IPv4Network(r["dst"]))
    for r in ip_j("-6", "route", "show", "table", "local", "type", "local"):
        local_v6.add(IPv6Network(r["dst"]))
    for iface in ip_j("address", "show"):
        for ai in iface["addr_info"]:
            if ai["family"] == "inet":
                ip4 = IPv4Network(ai["local"])
                local_v4.add(ip4)
            else:
                assert ai["family"] == "inet6"
                ip6 = IPv6Network(ai["local"])
                local_v6.add(ip6)
    local_v4 = set(collapse_addresses(local_v4))
    local_v6 = set(collapse_addresses(local_v6))
    return local_v4, local_v6


def output(ips: set[IPv4Network] | set[IPv6Network], v: int) -> None:
    print("# Generated by gen_local_ips.py")
    print(f"set local_addrs{v} {{")
    print(f"    type ipv{v}_addr")
    print("    flags constant, interval")
    print("    auto-merge")
    if ips:
        print(f"    elements = {{{', '.join(ip.compressed for ip in ips)}}}")
    print("}")


def generate() -> None:
    local_v4, local_v6 = fetch_ips()
    output(local_v4, 4)
    output(local_v6, 6)


def check() -> None:
    # Pass in nft -j list sets <tab_family tab_name>
    found_v4 = set()
    found_v6 = set()
    current = json.loads(sys.stdin.read())["nftables"]
    for item in current:
        if "metainfo" in item:
            assert item["metainfo"]["json_schema_version"] == 1
            continue
        if "set" not in item:
            eprint(f"Item not set: {item}")
            continue
        s = item["set"]
        if s["name"] == "local_addrs4":
            assert s["type"] == "ipv4_addr"
            for elem in s["elem"]:
                if isinstance(elem, str):
                    found_v4.add(IPv4Network(elem))
                else:
                    p = elem["prefix"]
                    found_v4.add(IPv4Network(f"{p['addr']}/{p['len']}"))
        elif s["name"] == "local_addrs6":
            assert s["type"] == "ipv6_addr"
            for elem in s["elem"]:
                if isinstance(elem, str):
                    found_v6.add(IPv6Network(elem))
                else:
                    p = elem["prefix"]
                    found_v6.add(IPv6Network(f"{p['addr']}/{p['len']}"))
    local_v4, local_v6 = fetch_ips()
    added_v4 = local_v4 - found_v4
    added_v6 = local_v6 - found_v6
    deleted_v4 = found_v4 - local_v4
    deleted_v6 = found_v6 - local_v6
    print("v4:")
    print("+ ", added_v4)
    print("- ", deleted_v4)
    print("v6:")
    print("+ ", added_v6)
    print("- ", deleted_v6)


if sys.argv[1] == "check":
    check()
elif sys.argv[1] == "gen":
    generate()
else:
    eprint("Unknown command")
